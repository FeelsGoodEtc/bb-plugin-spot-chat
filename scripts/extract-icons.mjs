// Extracts BB's built-in icon names from the installed BB app into icons.generated.ts.
// Usage: node scripts/extract-icons.mjs [path-to-bb.app]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const app = process.argv[2] ?? "/Applications/bb.app";
const assets = join(app, "Contents/Resources/app.asar.unpacked/node_modules/bb-app/app/dist/assets");
const names = new Set();
for (const file of readdirSync(assets).filter((name) => name.endsWith(".js"))) {
  const source = readFileSync(join(assets, file), "utf8");
  if (!source.includes("ICON_NAMES")) continue;
  const base = source.match(/=\{(AlertCircle:[^}]*)\}/);
  const extended = source.match(/=`(AiBrain01\.[A-Za-z0-9.]+)`/);
  if (!base || !extended) continue;
  for (const entry of base[1].split(",")) names.add(entry.split(":")[0].trim());
  for (const entry of extended[1].split(".")) names.add(entry.trim());
}
const valid = [...names].filter((name) => /^[A-Z][A-Za-z0-9]*$/.test(name)).sort();
if (valid.length < 50) throw new Error(`Found only ${valid.length} icon names in ${assets}`);
writeFileSync(
  new URL("../icons.generated.ts", import.meta.url),
  `// Generated by scripts/extract-icons.mjs from the installed BB app. Do not edit.\nexport const bbIconNames = ${JSON.stringify(valid, null, 2)} as const;\n`,
);
console.log(`Wrote ${valid.length} icon names.`);
